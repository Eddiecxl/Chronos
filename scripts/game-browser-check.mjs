import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const target = process.env.GAME_URL || 'http://127.0.0.1:4175/luoying-xiantu/index.html';
await mkdir('.artifacts', { recursive: true });
const errors = [];
const narrative = '我睁开眼，潮湿的木屑硌在掌心，雨水正沿着门缝流进屋里。我贴近木板，听见两种不同的脚步声：急促的那人停在院口，拖着脚的那人却从后窗绕了过去。窗外的灯影忽然熄灭，我借着月光看清窗闩上的一道新划痕。门外传来金属轻轻碰撞的响动，像是有人将钥匙插进了另一扇门。风从破窗灌入，吹开了搭在墙边的草席，露出半个沾泥的鞋印。我将这些细节记在心里，留意着脚步声离我的距离。';
for (const [label, viewport] of [['desktop', { width: 1440, height: 900 }], ['mobile', { width: 390, height: 844 }]]) {
  const context = await browser.newContext({ viewport, deviceScaleFactor: 1 });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await context.addInitScript(() => localStorage.setItem('chronos-session-token-v1', 'browser-test'));
  let calls = 0;
  await page.route('**/api/game/ai', async route => {
    const body = route.request().postDataJSON();
    calls++;
    if (calls > 1) {
      await new Promise(resolve => setTimeout(resolve, 800));
      await route.fulfill({ status: 429, json: { error: 'busy', retryAfterMs: 3000 } }).catch(() => {});
      return;
    }
    await route.fulfill({ json: { text: JSON.stringify({ blocks: [{ type: 'narr', text: narrative }], effects: {},
      progress: { advanced: ['opening:awakened'] }, memory: { facts: [] }, timeCost: 'brief' }), transactionId: body.transactionId } });
  });
  await page.goto(target);
  await page.click('#titleAiSettingsButton');
  await page.selectOption('#credentialSelect', 'personal');
  assert.equal(await page.inputValue('#baseUrlInput'), 'https://api.groq.com/openai/v1');
  await page.selectOption('#providerSelect', 'gemini');
  assert.equal(await page.inputValue('#baseUrlInput'), 'https://generativelanguage.googleapis.com/v1beta');
  await page.selectOption('#providerSelect', 'custom');
  await page.fill('#baseUrlInput', 'https://example.com/v1');
  await page.fill('#modelInput', 'test-model');
  await page.click('#saveAiButton');
  await page.click('[data-close="ai"]');
  await page.click('#titleAiSettingsButton');
  assert.equal(await page.inputValue('#baseUrlInput'), 'https://example.com/v1');
  await page.selectOption('#providerSelect', 'groq');
  await page.selectOption('#credentialSelect', 'site');
  await page.click('#saveAiButton');
  await page.click('[data-close="ai"]');
  await page.click('#newAiButton');
  await page.waitForSelector('.blk.narr');
  assert.equal(calls, 1);
  assert.equal(await page.locator('#retryPanel').isVisible(), false);
  const typography = await page.locator('.blk.narr .txt').evaluate(el => ({ font: getComputedStyle(el).fontFamily, size: getComputedStyle(el).fontSize }));
  assert.equal(typography.size, '16px');
  assert.match(typography.font, /Microsoft YaHei/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: `.artifacts/game-${label}.png` });
  await page.click('[data-open-panel="character"]');
  await page.waitForSelector('.equipment-slot');
  await page.locator('#panelLayer .modal').evaluate(el => Promise.all(el.getAnimations().map(a => a.finished)));
  assert.equal(await page.locator('.equipment-slot').count(), 7);
  await page.screenshot({ path: `.artifacts/character-${label}.png` });
  await page.click('[data-close="panel"]');
  await page.fill('#playerInput', '我仔细查看窗闩');
  await page.click('#sendButton');
  await page.waitForSelector('#pendingIndicator:not([hidden])');
  assert.equal(await page.locator('#playerInput').isEnabled(), true);
  await page.fill('#playerInput', '我准备问第二个问题');
  await page.waitForSelector('#retryPanel:not([hidden])');
  assert.equal(calls, 2, 'quota errors must not cause nested retries');
  assert.equal(await page.inputValue('#playerInput'), '我准备问第二个问题');
  await page.click('#editRetryButton');
  await page.fill('#playerInput', '我等待回应');
  await page.click('#sendButton');
  await page.click('#cancelAiButton');
  await page.waitForSelector('#retryPanel:not([hidden])');
  assert.match(await page.textContent('#retryMessage'), /停止等待/);
  assert.equal(await page.locator('.blk.narr').count(), 1);
  await page.click('#systemChannel');
  await page.fill('#playerInput', '我的面板');
  await page.click('#sendButton');
  await page.waitForSelector('.blk.sys');
  assert.equal(await page.locator('.blk.narr').count(), 1);
  await page.reload();
  await page.click('#continueAiButton');
  await page.waitForSelector('.blk.narr');
  console.log(JSON.stringify({ label, typography, calls, restored: true, errors }));
  await context.close();
}
await browser.close();
assert.deepEqual(errors, []);
